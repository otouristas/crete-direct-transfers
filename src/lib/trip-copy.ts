export function tripCopy(locale: Locale, driver = false): Copy {
  const copy = localized[locale] ?? en;
  if (!driver) return copy;
  const phases = ["assigned", "to_pickup", "at_pickup", "on_trip", "completed"];
  return {
    ...copy,
    phases: {
      ...copy.phases,
      ...Object.fromEntries(phases.map((phase, i) => [phase, driverLabels[locale][i]])),
    },
  };
}
